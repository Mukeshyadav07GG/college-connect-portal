import jsPDF from "jspdf";

export interface ReceiptData {
  receiptNo: string;
  studentName: string;
  rollNumber: string;
  section: string;
  semester: string;
  totalFee: number;
  paidThisTransaction: number;
  remainingAmount: number;
  generatedBy: string;
  date: Date;
}

export const generateReceiptPDF = (d: ReceiptData): Blob => {
  const doc = new jsPDF({ unit: "pt", format: "a4" });
  const W = doc.internal.pageSize.getWidth();

  // Header band
  doc.setFillColor(30, 58, 138);
  doc.rect(0, 0, W, 90, "F");
  doc.setTextColor(255, 255, 255);
  doc.setFont("helvetica", "bold");
  doc.setFontSize(16);
  doc.text("Dr. K.N. Modi Institute of Engineering and Technology", W / 2, 38, { align: "center" });
  doc.setFont("helvetica", "normal");
  doc.setFontSize(11);
  doc.text("Modinagar, Ghaziabad, Uttar Pradesh", W / 2, 58, { align: "center" });
  doc.setFontSize(13);
  doc.setFont("helvetica", "bold");
  doc.text("FEE RECEIPT", W / 2, 78, { align: "center" });

  // Watermark
  doc.setTextColor(220, 220, 220);
  doc.setFontSize(90);
  doc.setFont("helvetica", "bold");
  // @ts-ignore — angle param
  doc.text("PAID", W / 2, 480, { align: "center", angle: 30 });

  // Body text
  doc.setTextColor(20, 20, 20);
  doc.setFont("helvetica", "normal");
  doc.setFontSize(11);

  const leftX = 50;
  let y = 130;
  doc.setFont("helvetica", "bold");
  doc.text("Receipt No:", leftX, y);
  doc.setFont("helvetica", "normal");
  doc.text(d.receiptNo, leftX + 90, y);

  doc.setFont("helvetica", "bold");
  doc.text("Date:", W - 200, y);
  doc.setFont("helvetica", "normal");
  doc.text(d.date.toLocaleString(), W - 160, y);

  y += 30;
  doc.setFont("helvetica", "bold");
  doc.setFontSize(12);
  doc.text("Student Details", leftX, y);
  doc.setLineWidth(0.5);
  doc.line(leftX, y + 4, W - 50, y + 4);

  y += 22;
  doc.setFontSize(11);
  const row = (k: string, v: string) => {
    doc.setFont("helvetica", "bold");
    doc.text(k, leftX, y);
    doc.setFont("helvetica", "normal");
    doc.text(v || "—", leftX + 130, y);
    y += 18;
  };
  row("Name:", d.studentName);
  row("Roll Number:", d.rollNumber);
  row("Section:", d.section);
  row("Semester:", d.semester);

  y += 14;
  doc.setFont("helvetica", "bold");
  doc.setFontSize(12);
  doc.text("Payment Details", leftX, y);
  doc.line(leftX, y + 4, W - 50, y + 4);
  y += 18;

  // Table
  const tableX = leftX;
  const tableW = W - leftX * 2;
  doc.setFillColor(240, 244, 255);
  doc.rect(tableX, y, tableW, 24, "F");
  doc.setFont("helvetica", "bold");
  doc.setFontSize(11);
  doc.text("Description", tableX + 10, y + 16);
  doc.text("Amount (INR)", tableX + tableW - 10, y + 16, { align: "right" });
  y += 24;

  const trow = (k: string, v: number, bold = false) => {
    doc.setFont("helvetica", bold ? "bold" : "normal");
    doc.text(k, tableX + 10, y + 16);
    doc.text(`Rs. ${v.toLocaleString("en-IN")}`, tableX + tableW - 10, y + 16, { align: "right" });
    doc.setLineWidth(0.2);
    doc.line(tableX, y + 24, tableX + tableW, y + 24);
    y += 24;
  };
  trow("Total Fee", d.totalFee);
  trow("Paid (This Transaction)", d.paidThisTransaction, true);
  trow("Remaining Amount", d.remainingAmount);

  y += 30;
  doc.setFont("helvetica", "italic");
  doc.setFontSize(10);
  doc.setTextColor(80, 80, 80);
  doc.text(`Generated by: ${d.generatedBy}`, leftX, y);

  // Footer
  doc.setDrawColor(200);
  doc.line(leftX, 780, W - leftX, 780);
  doc.setFont("helvetica", "italic");
  doc.setFontSize(9);
  doc.setTextColor(120, 120, 120);
  doc.text("System Generated Receipt — no signature required.", W / 2, 800, { align: "center" });

  return doc.output("blob");
};

export const buildReceiptNo = (): string => {
  const year = new Date().getFullYear();
  const seq = Math.floor(1000 + Math.random() * 9000);
  return `ERP-${year}-${seq}`;
};
